"use client";

import { FormEvent, useState } from "react";
import { login } from "../lib/api";

export default function LoginForm() {
  const [username, setUsername] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState("");
  const [saving, setSaving] = useState(false);

  async function submit(event: FormEvent) {
    event.preventDefault();
    setSaving(true);
    setError("");
    try {
      await login(username.trim(), password);
      window.location.href = "/";
    } catch (e) {
      const message = e instanceof Error ? e.message : "Sign in failed";
      if (message === "TERMINAL_REENROLLMENT_REQUIRED") {
        setError("This terminal is not registered. Register it before signing in.");
      } else if (message === "FORBIDDEN") {
        setError("This account does not have POS access.");
      } else {
        setError(message);
      }
    } finally {
      setSaving(false);
    }
  }

  return (
    <main className="pos-auth-shell">
      <section className="pos-auth-panel" aria-label="Cashier sign in">
        <div className="pos-auth-brand">
          <img src="/lingo-logo.svg" alt="Lingo" />
          <span>POS</span>
        </div>
        <div className="pos-auth-intro">
          <p className="pos-auth-kicker">Cashier access</p>
          <h1>Sign in to this terminal</h1>
          <p>Use a staff account with POS access. This terminal must be registered before sign-in.</p>
        </div>
        <form className="pos-auth-form" onSubmit={submit}>
          <label>
            <span>Username</span>
            <input
              value={username}
              onChange={(e) => setUsername(e.target.value)}
              autoComplete="username"
              autoFocus
              required
            />
          </label>
          <label>
            <span>Password</span>
            <input
              type="password"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              autoComplete="current-password"
              required
            />
          </label>
          {error && <p className="pos-auth-error" role="alert">{error}</p>}
          <button className="pos-auth-submit" disabled={saving}>
            {saving ? "Signing in…" : "Sign in"}
          </button>
        </form>
        <div className="pos-auth-divider"><span>Terminal setup</span></div>
        <a className="pos-auth-secondary" href="/enroll">Register this terminal</a>
        <p className="pos-auth-footnote">Enrollment requires a one-time code generated by an administrator.</p>
      </section>
      <aside className="pos-auth-side" aria-hidden="true">
        <div className="pos-auth-side-mark">L</div>
        <strong>Fast checkout.<br />Clear control.</strong>
        <span>Designed for the Lingo Store counter.</span>
      </aside>
    </main>
  );
}
